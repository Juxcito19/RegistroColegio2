    private void btnRegistrarEstudianteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarEstudianteActionPerformed
        try {
            if (txtNombre.getText().trim().isEmpty()) {
                throw new IllegalArgumentException("El nombre es obligatorio");
            }
            modelo.Estudiante e = new modelo.Estudiante();
            e.setNombre(txtNombre.getText().trim());
            e.setDireccion(txtDireccion.getText().trim());
            e.setTelefono(txtTelefono.getText().trim());
            e.setFechaNacimiento(java.time.LocalDate.parse(txtFecha.getText().trim()));
            e.setCodigo(txtCodigo.getText().trim());
            e.setGrado(txtGrado.getText().trim());
            colegio.registrarEstudiante(e);
            lblEstado.setText("Estudiante registrado: " + e.getNombre());
            limpiarCampos();
        } catch (Exception ex) {
            lblEstado.setText("Datos inválidos: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarEstudianteActionPerformed

    private void btnRegistrarProfesorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarProfesorActionPerformed
        try {
            if (txtNombre.getText().trim().isEmpty()) {
                throw new IllegalArgumentException("El nombre es obligatorio");
            }
            double extra = Double.parseDouble(txtExtra.getText().trim());
            modelo.Profesor p;
            if (cmbTipo.getSelectedItem().toString().equals("Planta")) {
                modelo.ProfesorPlanta pp = new modelo.ProfesorPlanta();
                pp.setAniosAntiguedad((int) extra);
                p = pp;
            } else {
                p = new modelo.ProfesorCatedra(extra);
            }
            p.setNombre(txtNombre.getText().trim());
            p.setDireccion(txtDireccion.getText().trim());
            p.setTelefono(txtTelefono.getText().trim());
            p.setFechaNacimiento(java.time.LocalDate.parse(txtFecha.getText().trim()));
            if (p.calcularEdad() < 18) {
                throw new IllegalArgumentException("El profesor debe ser mayor de edad");
            }
            p.setCedula(txtCedula.getText().trim());
            p.setArea(txtArea.getText().trim());
            p.setSalarioHora(Double.parseDouble(txtSalarioHora.getText().trim()));
            p.setHorasDictadas(Integer.parseInt(txtHoras.getText().trim()));
            colegio.registrarProfesor(p);
            lblEstado.setText("Profesor registrado: " + p.getNombre());
            limpiarCampos();
        } catch (Exception ex) {
            lblEstado.setText("Datos inválidos: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarProfesorActionPerformed

